// Interfaces
interface SelectOption {
  value: string;
  label: string;
  disabled?: boolean;
}

interface CustomSelectProps {
  options: SelectOption[];
  placeholder?: string;
  value?: string;
  onValueChange?: (value: string) => void;
  disabled?: boolean;
  className?: string;
}

// Componente CustomSelect simplificado sin React.memo que causaba el loop
const CustomSelect: React.FC<CustomSelectProps> = ({
  options,
  placeholder = "Selecciona una opción...",
  value,
  onValueChange,
  disabled = false,
  className
}) => {
  return (
    <Select value={value} onValueChange={onValueChange} disabled={disabled}>
      <SelectTrigger className={className}>
        <SelectValue placeholder={placeholder} />
      </SelectTrigger>
      <SelectContent>
        {options.map((option) => (
          <SelectItem 
            key={option.value} 
            value={option.value}
            disabled={option.disabled}
          >
            {option.label}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  );
};

CustomSelect.displayName = "CustomSelect";

// Ejemplo de uso correcto
const ExampleUsage: React.FC = () => {
  const [selectedValue, setSelectedValue] = React.useState<string>("");
  
  // Opciones estables definidas fuera del render
  const options: SelectOption[] = [
    { value: "option1", label: "Opción 1" },
    { value: "option2", label: "Opción 2" },
    { value: "option3", label: "Opción 3" },
    { value: "option4", label: "Opción 4", disabled: true },
  ];

  const handleSelectionChange = (value: string) => {
    console.log("Valor seleccionado:", value);
    setSelectedValue(value);
  };

  return (
    <div className="p-4 space-y-4">
      <h2 className="text-lg font-semibold">Ejemplo de Select Component</h2>
      
      <div className="w-64">
        <label className="block text-sm font-medium text-gray-700 mb-2">
          Selecciona una opción:
        </label>
        <CustomSelect
          options={options}
          value={selectedValue}
          onValueChange={handleSelectionChange}
          placeholder="Elige una opción..."
          className="w-full"
        />
      </div>
      
      {selectedValue && (
        <p className="text-sm text-gray-600">
          Valor seleccionado: <strong>{selectedValue}</strong>
        </p>
      )}
    </div>
  );
};

export {
  Select,
  SelectGroup,
  SelectValue,
  SelectTrigger,
  SelectContent,
  SelectLabel,
  SelectItem,
  SelectSeparator,
  SelectScrollUpButton,
  SelectScrollDownButton,
  CustomSelect,
  ExampleUsage
}